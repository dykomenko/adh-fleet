#!/usr/bin/env bash
#
# Снимает шаблон конфига с настроенной origin-ноды. Запускается НА ORIGIN.
#
#   VPN_GW=10.101.0.1 ./make-template.sh
#
# Результат — node/AdGuardHome.yaml.tmpl, который коммитится в репозиторий.
# Секретов в нём нет: адреса и bcrypt-хеш пароля заменены плейсхолдерами,
# а подставляются они уже на ноде во время установки.
#
# Переснимать нужно только если поменялись bind-адреса или пароль админа.
# Фильтры и правила в шаблоне не важны — они приезжают синхронизацией.

set -euo pipefail

CONF=/opt/adguardhome/conf/AdGuardHome.yaml
OUT="${1:-/tmp/AdGuardHome.yaml.tmpl}"

[[ -f "$CONF" ]] || { echo "нет $CONF — origin ещё не настроен" >&2; exit 1; }
command -v jq >/dev/null || { echo "нужен jq" >&2; exit 1; }

NB_IP="$(netbird status --json | jq -r '.netbirdIp // empty' | cut -d/ -f1)"
[[ -n "$NB_IP" ]] || { echo "не удалось определить адрес ноды в оверлее" >&2; exit 1; }

# bcrypt-хеш из секции users — он же понадобится как AGH_PASS_HASH при установке
HASH="$(grep -oE '\$2[aby]\$[0-9]{2}\$[A-Za-z0-9./]{53}' "$CONF" | head -1)"
[[ -n "$HASH" ]] || { echo "не нашёл bcrypt-хеш пароля в $CONF" >&2; exit 1; }

# Списки фильтров и пользовательские правила из шаблона вырезаются.
#
# Во-первых, они там не нужны: на реплики всё это приезжает синхронизацией
# с origin, шаблону достаточно поднять AGH с правильными адресами и паролем.
# Во-вторых, репозиторий публичный, а user_rules — личный список исключений,
# по которому видно, какими сервисами вы пользуетесь.
sed -e "s|${HASH//\//\\/}|__PASS_HASH__|g" "$CONF" \
  | awk '
      /^(filters|whitelist_filters|user_rules):/ { skip = 1; print $1 " []"; next }
      skip && /^[a-zA-Z_]+:/                    { skip = 0 }
      !skip                                     { print }
    ' > "$OUT"

grep -q '__PASS_HASH__' "$OUT" || { echo "плейсхолдер __PASS_HASH__ не подставился" >&2; exit 1; }

# И DNS, и панель должны слушать все интерфейсы. Адреса у нод разные,
# поэтому любая привязка к конкретному адресу сделает шаблон непригодным
# для реплик. Доступ ограничивает iptables, а не bind-адрес.
if grep -qE "^\s*-?\s*${NB_IP}\s*$|^\s*address:\s*${NB_IP}:" "$OUT"; then
  echo "ОТКАЗ: в конфиге осталась привязка к адресу этой ноды ($NB_IP)." >&2
  echo "В мастере AGH и для DNS, и для веб-интерфейса должно быть выбрано" >&2
  echo "«Все интерфейсы» — иначе реплики получат чужой адрес и не поднимутся." >&2
  exit 1
fi

# Страховка: убедиться, что в шаблон не утёк ни один bcrypt-хеш
if grep -qE '\$2[aby]\$[0-9]{2}\$' "$OUT"; then
  echo "в шаблоне остался bcrypt-хеш — публиковать нельзя" >&2
  exit 1
fi

for k in filters whitelist_filters user_rules; do
  grep -qE "^${k}: \[\]" "$OUT" || { echo "не удалось вырезать блок $k" >&2; exit 1; }
done

echo "шаблон готов: $OUT"
echo "фильтры и user_rules вырезаны — они приедут на реплики синхронизацией"
echo "секретов не содержит, коммитьте в node/AdGuardHome.yaml.tmpl"
echo
echo "хеш пароля для установки нод (AGH_PASS_HASH):"
echo "$HASH"
